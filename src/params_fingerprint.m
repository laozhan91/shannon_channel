function fp = params_fingerprint(cfg)
%PARAMS_FINGERPRINT 生成标定缓存指纹：物理参数变化时会自动重新标定
parts = { ...
    sprintf('blk=%d',  cfg.turbo.blockLen), ...
    sprintf('iter=%d', cfg.turbo.nIter), ...
    sprintf('gen=%s',  mat2str(cfg.turbo.genPoly)), ...
    sprintf('alg=%s',  cfg.turbo.algorithm), ...
    sprintf('eng=%s',  cfg.turbo.engine), ...
    sprintf('tgt=%g',  cfg.targetBER), ...
    sprintf('combo=%s', mat2str(cfg.comboTable, 8)), ...
    sprintf('cal=%.4g/%.4g/%.4g/%.4g/%.4g/%.4g', cfg.calib.minBits, cfg.calib.maxBits, ...
            cfg.calib.targetErrors, cfg.calib.coarseStep_dB, cfg.calib.fineStep_dB, cfg.calib.margin_dB), ...
    sprintf('seed=%d', cfg.seed)};
fp = strjoin(parts, '|');
end
